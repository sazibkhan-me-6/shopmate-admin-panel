function build200Products(): CatalogProduct[] {
  const result: CatalogProduct[] = [...FLAGSHIP_PRODUCTS];
  let nextId = 13;

  for (const group of CATEGORY_SEEDS) {
    group.items.forEach(([name, price, discountPercent, stock], idx) => {
      const discountedPrice = Math.round(price * (1 - discountPercent / 100));
      const status: CatalogProduct['status'] =
        stock <= 12 ? 'Low stock' : idx % 19 === 18 ? 'Draft' : 'Active';
      result.push({
        id: nextId,
        name,
        sku: `${group.prefix}-${String(1000 + nextId)}`,
        category: group.category,
        price,
        discountPercent,
        discountedPrice,
        stock,
        status,
        image: group.images[idx % group.images.length],
      });
      nextId += 1;
    });
  }

  return result;
}

export const INITIAL_200_PRODUCTS: CatalogProduct[] = build200Products();
